import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { requireTestDatabase } from "./test-database-guard.mjs";
requireTestDatabase(process.env);
Object.assign(process.env, { DISCORD_TOKEN: "test", DISCORD_CLIENT_ID: "test", OPENAI_API_KEY: "test", AI_MIN_INTERVAL_MS: "0", AI_MAX_RETRIES: "0" });
const prefix = `history-${randomUUID()}`, guilds = Array.from({ length: 7 }, (_, index) => `${prefix}-${index}`);
const originalFetch = globalThis.fetch;
let stage = "setup", generated = [], requests = [], review = true, sent = [];
const specimen = (question, answer = "Wombat", explanation = "A synthetic animal fact.") => ({ language: "pl", topic: "Zwierzęta", question, options: [answer, "Koala", "Bóbr", "Kapibara"], correctOption: 0, explanation, topicEmoji: "", optionEmojis: ["", "", "", ""] });
const original = specimen("Który ssak produkuje odchody o kształcie kostek?");
const paraphrase = specimen("Jakie zwierzę wydala kał w postaci sześcianów?");
const fresh = specimen("Który ptak potrafi unosić się w powietrzu w miejscu?", "Koliber", "Synthetic hummingbird fact.");
globalThis.fetch = async (url, options) => {
  assert.equal(String(url), "https://api.openai.com/v1/responses");
  const body = JSON.parse(options.body); requests.push(body);
  const value = body.text.format.name === "quiz_novelty" ? { duplicate: review === "invalid" ? "false" : review } : generated.shift();
  if (!value) throw new Error("Unexpected synthetic AI request");
  return new Response(JSON.stringify({ object: "response", status: "completed", output: [{ type: "message", content: [{ type: "output_text", text: JSON.stringify(value) }] }] }), { headers: { "content-type": "application/json" } });
};
const { db } = await import("../dist/db.js");
const { publishTopicQuestions, publishRandomQuestion } = await import("../dist/services/poll-publisher.js");
const { loadQuestionHistory, loadQuestionFacts } = await import("../dist/services/question-history.js");
const { quizDay } = await import("../dist/services/quiz-limits.js");
const originalGeneratedRead = db.generatedPoll.findMany.bind(db.generatedPoll), originalRandomRead = db.randomPoll.findMany.bind(db.randomPoll);
const poll = (guildId, messageId, data = original, createdAt = new Date(1000)) => ({ guildId, messageId, channelId: "test-channel", question: data.question, options: JSON.stringify(data.options), correctOption: data.correctOption, explanation: data.explanation, createdAt });
const channel = guildId => ({ id: "test-channel", guild: { id: guildId, members: {} }, send: async payload => { sent.push(payload); return { id: `${prefix}-sent-${sent.length}` }; } });
const topic = guildId => db.topic.create({ data: { guildId, name: "Synthetic wildlife", channelId: "test-channel", options: "", optionCount: 4, startDate: quizDay(new Date()), generationTime: "00:00" } });
const setLanguage = guildId => db.guildSettings.create({ data: { guildId, language: "pl" } });
function scenario(values, duplicate = true) { generated = [...values]; requests = []; review = duplicate; }
try {
  for (const guildId of guilds) await setLanguage(guildId);
  stage = "random-to-topic";
  const first = await topic(guilds[0]);
  await db.randomPoll.create({ data: { ...poll(guilds[0], `${prefix}-random-old`), language: "pl" } });
  scenario([paraphrase, fresh]);
  await publishTopicQuestions(first, channel(guilds[0]));
  assert.deepEqual(requests.map(row => row.text.format.name), ["quiz_question", "quiz_novelty", "quiz_question"]);
  assert.ok(requests[0].input.includes(original.question));
  assert.ok(requests[2].input.includes(paraphrase.question));
  assert.equal((await db.generatedPoll.findFirst({ where: { guildId: guilds[0] } })).question, fresh.question);
  assert.equal(sent.length, 1, "The rejected paraphrase never reaches Discord");
  stage = "topic-to-random";
  await db.generatedPoll.create({ data: { ...poll(guilds[1], `${prefix}-topic-deleted`), topicId: "removed-topic" } });
  scenario([paraphrase, fresh]);
  await publishRandomQuestion(guilds[1], 4, channel(guilds[1]));
  assert.deepEqual(requests.map(row => row.text.format.name), ["quiz_question", "quiz_novelty", "quiz_question"]);
  assert.equal((await db.randomPoll.findFirst({ where: { guildId: guilds[1] } })).question, fresh.question);
  stage = "different-fact";
  const third = await topic(guilds[2]);
  await db.randomPoll.create({ data: { ...poll(guilds[2], `${prefix}-same-animal`), language: "pl" } });
  const different = specimen("Które zwierzę wykopuje rozbudowane podziemne nory?", "Wombat", "A distinct synthetic burrow fact.");
  scenario([different], false); await publishTopicQuestions(third, channel(guilds[2]));
  assert.equal(requests.length, 2); assert.equal((await db.generatedPoll.findFirst({ where: { guildId: guilds[2] } })).question, different.question);
  stage = "guild-isolation";
  const isolated = await topic(guilds[3]);
  scenario([original]); await publishTopicQuestions(isolated, channel(guilds[3]));
  assert.equal(requests.length, 1, "Another server's history causes neither a retry nor a review");
  stage = "failure-closed";
  const failing = await topic(guilds[4]);
  await db.randomPoll.create({ data: { ...poll(guilds[4], `${prefix}-blocked`), language: "pl" } });
  scenario([paraphrase, original, paraphrase]);
  const before = sent.length;
  await assert.rejects(publishTopicQuestions(failing, channel(guilds[4])));
  assert.equal(sent.length, before); assert.equal(await db.generatedPoll.count({ where: { guildId: guilds[4] } }), 0);
  assert.equal(await db.dailyQuizRun.count({ where: { guildId: guilds[4] } }), 0, "Failed novelty checks release unused quiz slots");
  scenario([paraphrase], "invalid");
  await assert.rejects(publishTopicQuestions(failing, channel(guilds[4])));
  assert.equal(sent.length, before); assert.equal(requests.length, 2);
  assert.equal(await db.dailyQuizRun.count({ where: { guildId: guilds[4] } }), 0, "An invalid review cannot bypass protection or consume a quiz slot");
  stage = "parallel-publication";
  const one = await topic(guilds[5]);
  const two = await db.topic.create({ data: { ...one, id: undefined, name: "Another synthetic topic" } });
  scenario([original, paraphrase, fresh]);
  await Promise.all([publishTopicQuestions(one, channel(guilds[5])), publishTopicQuestions(two, channel(guilds[5]))]);
  const rows = await db.generatedPoll.findMany({ where: { guildId: guilds[5] }, orderBy: { createdAt: "asc" } });
  assert.deepEqual(rows.map(row => row.question), [original.question, fresh.question]);
  assert.equal(requests.filter(row => row.text.format.name === "quiz_novelty").length, 1);
  stage = "bounded-indexed-history";
  const retained = await topic(guilds[6]);
  await db.topic.update({ where: { id: retained.id }, data: { questionsGenerated: 400 } });
  const own = Array.from({ length: 366 }, (_, index) => ({ ...poll(guilds[6], `${prefix}-own-${index}`, specimen(`Older own fixture ${index}?`), new Date(100000 - index)), topicId: retained.id }));
  const global = Array.from({ length: 366 }, (_, index) => ({ ...poll(guilds[6], `${prefix}-global-${index}`, specimen(`Recent different fixture ${index}?`), new Date(200000 - index)), topicId: "other-topic" }));
  const random = Array.from({ length: 1461 }, (_, index) => ({ ...poll(guilds[6], `${prefix}-random-${index}`, specimen(`Random fixture ${index}?`), new Date(300000 - index)), language: "pl", category: `Category ${index}` }));
  await db.generatedPoll.createMany({ data: [...own, ...global] }); await db.randomPoll.createMany({ data: random });
  const reads = [];
  db.generatedPoll.findMany = async request => { reads.push(request); return originalGeneratedRead(request); };
  db.randomPoll.findMany = async request => { reads.push(request); return originalRandomRead(request); };
  const loaded = await loadQuestionHistory(guilds[6], { id: retained.id, questionsGenerated: 400 });
  assert.equal(reads.length, 3); assert.ok(reads.every(request => request.where.guildId === guilds[6] && !request.select.explanation));
  assert.equal(loaded.questions.length, 365 + 365 + 1460);
  assert.equal(loaded.questions[0].question, "Random fixture 0?");
  assert.ok(loaded.questions.some(row => row.question === "Older own fixture 364?"));
  assert.ok(!loaded.questions.some(row => row.source === "topic" && /fixture 365\?/.test(row.question)));
  assert.ok(!loaded.questions.some(row => row.question === "Random fixture 1460?"));
  assert.ok(loaded.questions.some(row => row.question === "Random fixture 365?"));
  assert.equal(loaded.categories.length, 64);
  reads.length = 0;
  const candidates = loaded.questions.slice(0, 5);
  const facts = await loadQuestionFacts(guilds[6], candidates);
  assert.equal(reads.length, 1); assert.equal(reads[0].take, 5); assert.equal(facts.length, 5);
  assert.ok(reads[0].select.explanation);
  assert.deepEqual(reads[0].select, { id: true, explanation: true });
  db.generatedPoll.findMany = originalGeneratedRead; db.randomPoll.findMany = originalRandomRead;
  const index = await db.$queryRawUnsafe("SELECT indexname FROM pg_indexes WHERE tablename='GeneratedPoll' AND indexname='GeneratedPoll_guildId_topicId_createdAt_idx'");
  assert.equal(index.length, 1);
  const migration = readFileSync("prisma/postgresql/migrations/20261104090000_shared_question_history_index/migration.sql", "utf8");
  assert.equal(migration, readFileSync("prisma/migrations/20261104090000_shared_question_history_index/migration.sql", "utf8"));
  console.log(JSON.stringify({ check: "question-history-postgres", passed: true, crossSource: true, deletedTopicHistory: true, differentFactsAllowed: true, guildIsolation: true, parallelPublication: true, reservationsReleased: true, boundedHistory: true, leanReads: true, indexed: true, liveApiUsed: false }));
} catch (error) {
  console.error(JSON.stringify({ check: "question-history-postgres", passed: false, stage, category: error instanceof assert.AssertionError ? "assertion" : "test-error", errorType: /^[A-Za-z]+Error$/.test(error.name) ? error.name : "Error", kind: ["unavailable", "limit", "configuration", "invalid-response", "timeout"].includes(error.kind) ? error.kind : undefined, requests: requests.map(request => request.text?.format?.name), remaining: generated.length, line: Number(error.stack?.match(/test-question-history-postgres\.mjs:(\d+)/)?.[1] ?? 0) })); process.exitCode = 1;
} finally {
  globalThis.fetch = originalFetch; db.generatedPoll.findMany = originalGeneratedRead; db.randomPoll.findMany = originalRandomRead;
  await db.quizSettlement.deleteMany({ where: { guildId: { in: guilds } } });
  for (const table of ["generatedPoll", "randomPoll", "dailyQuizRun", "topic", "guildSettings"]) await db[table].deleteMany({ where: { guildId: { in: guilds } } });
  await db.$disconnect();
}
