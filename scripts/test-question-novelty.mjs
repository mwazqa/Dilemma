import assert from "node:assert/strict";
import { QuestionNoveltyIndex, normalizeQuestion, withQuestionPublication } from "../dist/services/question-novelty.js";
const row = (question, correctAnswer, index = 0, extra = {}) => ({ id: String(index), source: "random", question, correctAnswer, createdAt: new Date(100000 - index), ...extra });
const original = row("Jakie zwierzę produkuje odchody przypominające kostki?", "Wombat");
const history = [original, row("Gdzie żyje wombat?", "Australia", 1), row("Jakie miasto jest stolicą Francji?", "Paryż", 2)];
const index = new QuestionNoveltyIndex(history);
assert.ok(index.hasExact("  JAKIE ZWIERZĘ produkuje odchody przypominające kostki! "));
assert.equal(index.candidates("Który ssak wydala kał w kształcie sześcianów?", "Wombat")[0].id, original.id);
assert.equal(index.candidates("Jaki kształt mają odchody wombata?", "Kostki")[0].id, original.id, "Reversing question/answer direction still selects the earlier fact");
assert.ok(index.candidates("Which animal produces cube-shaped droppings?", "Wombat").some(row => row.id === original.id));
assert.ok(index.candidates("U kogo ekskrementy są sześcienne?", "Wombaty").some(row => row.id === original.id), "Inflected answers still identify a possible paraphrase");
const translated = new QuestionNoveltyIndex([row("Which city is the capital of Poland?", "Warsaw")]);
assert.equal(translated.candidates("Jakie miasto jest stolicą Polski?", "Warszawa").length, 1);
assert.equal(index.candidates("Który pierwiastek ma symbol Au?", "Złoto").length, 0, "Unrelated facts need no review request");
assert.equal(index.hasExact("Gdzie wombaty wychowują młode?"), false, "An animal is not globally banned after one question");
assert.notEqual(normalizeQuestion("Czy temperatura wynosi -5 stopni?"), normalizeQuestion("Czy temperatura wynosi 5 stopni?"));
assert.notEqual(normalizeQuestion("Czy to prawda?"), normalizeQuestion("Czy to nieprawda?"));
index.reject("Nieudana próba?"); assert.ok(index.hasExact("NIEUDANA PRÓBA!"));
const many = new QuestionNoveltyIndex(Array.from({ length: 2000 }, (_, i) => row(`Synthetic subject ${i}?`, `Synthetic answer ${i}`, i)));
const prompt = many.prompt();
assert.equal(prompt.length, 20); assert.equal(prompt[0], "Synthetic subject 0?"); assert.equal(prompt.at(-1), "Synthetic subject 19?");
assert.ok(!prompt.includes("Synthetic subject 1999?"), "The prompt contains the newest rather than oldest history");
assert.equal(many.prompt(undefined, ["Rejected new attempt?"])[0], "Rejected new attempt?");
assert.ok(many.candidates("Which synthetic subject has this answer?", "Synthetic answer 1999").length <= 5);
const yes = new QuestionNoveltyIndex([row("Czy pingwiny potrafią latać?", "Nie")]);
assert.equal(yes.candidates("Czy złoto jest magnetyczne?", "Nie").length, 0);
const ordered = [], pause = {};
const wait = new Promise(resolve => pause.resolve = resolve);
const first = withQuestionPublication("same", async () => { ordered.push("first-start"); await wait; ordered.push("first-saved"); });
const second = withQuestionPublication("same", async () => { ordered.push("second-read"); });
await withQuestionPublication("other", async () => { ordered.push("other"); });
assert.deepEqual(ordered, ["first-start", "other"]);
pause.resolve(); await Promise.all([first, second]);
assert.deepEqual(ordered, ["first-start", "other", "first-saved", "second-read"]);
await assert.rejects(withQuestionPublication("same", async () => { throw new Error("Synthetic failure"); }), /Synthetic/);
assert.equal(await withQuestionPublication("same", async () => "recovered"), "recovered");
console.log(JSON.stringify({ check: "question-novelty", passed: true, recentPrompt: true, boundedCandidates: true, inverseQuestion: true, guildQueue: true, failureRecovery: true }));
